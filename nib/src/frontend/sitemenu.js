// The sidebar's ☰ Menu face: the folder's docs-site menus as the SITE will
// show them — VitePress's sidebar, a GitBook SUMMARY, mkdocs.yml's nav —
// rather than as the folders lie on disk. The backend (menus.js) reads every
// system into one shape; this only draws it, and asks for edits.
//
// It behaves like the file tree: one click previews, a double-click keeps
// (and opens a group that is also a page), ↑↓ walk the rows, ←→ fold, ⏎
// renames in place, ⌘↑/⌘↓ move an entry among its siblings, ⌘⌫ removes it,
// and ⌘Z/⇧⌘Z take edits back while the panel has the keyboard. Drag moves
// rows; a page dragged up from "Not in any menu" is added.
//
// The head is one line — the system, the menu picker, a red count of dead
// entries — with ⓘ for the rest: where the menu is written, what's built by
// code, where this page sits.

(() => {
  function setupSiteMenu({ box, fetch, root, onOpen, onOpenAt, onExternal, onChange, onEdit, onUndo, onRedo,
    showMenu, toast, onEscape, onFocus }) {
    const $ = (id) => box.querySelector('#' + id);
    let sites = [];
    let current = null;              // project-relative path of the shown doc
    let chosen = null;               // menu key the person picked
    let shown = null;                // menu key on screen now
    let ask = 0;
    const shut = new Map();          // menu key -> Set of item ids folded by hand
    const opened = new Map();        // ... and ones opened by hand (beats collapsed: true)
    let orphansOpen = false;
    let drag = null;                 // { at } a menu entry, or { file } an orphan
    let cursor = null;               // keyboard cursor: an item id in the shown menu
    let renaming = null;             // item id being renamed in place
    let typed = null;                // what's typed there, kept across repaints
    let rows = [];                   // the visible rows, top to bottom: { id, it, kids, isShut }
    let infoOpen = false;
    let previewTimer = null;

    const KEY = 'nib.sitemenu.chosen', INFO = 'nib.sitemenu.info';
    try { chosen = localStorage.getItem(KEY); infoOpen = localStorage.getItem(INFO) === '1'; } catch { /* fine */ }
    box.tabIndex = 0;                // focusable, like the tree, for the keys

    const menus = () => sites.flatMap((s) => s.menus.map((m) => ({ site: s, menu: m })));
    const abs = (rel) => (root() ? root() + '/' + rel : rel);
    const itemAt = (menu, id) => {
      let list = menu.items, it = null;
      for (const k of String(id).split('.')) { it = list && list[+k]; if (!it) return null; list = it.items; }
      return it;
    };
    const parentId = (id) => (id.includes('.') ? id.slice(0, id.lastIndexOf('.')) : null);

    // the trail to `rel` in one menu's items, as item ids — or null
    function trailTo(items, rel, pre = '') {
      for (let i = 0; i < (items || []).length; i++) {
        const it = items[i];
        const id = pre + i;
        if (it.file === rel) return [id];
        const sub = trailTo(it.items, rel, id + '.');
        if (sub) return [id, ...sub];
      }
      return null;
    }
    const textAt = (items, ids) => {
      const out = [];
      let list = items;
      for (const id of ids) {
        const it = list[+id.split('.').pop()];
        out.push(it.text || '(untitled)');
        list = it.items || [];
      }
      return out;
    };

    // The menu to show. A pick sticks; only moving to a page the menu on
    // screen doesn't have switches it — to the picked one if that has the
    // page, else the first that does.
    function follow() {
      const all = menus();
      const has = (k) => { const x = all.find((y) => y.menu.key === k); return x && current && trailTo(x.menu.items, current); };
      if (shown && has(shown)) return;
      if (chosen && has(chosen)) { shown = chosen; return; }
      const holds = current && all.find((x) => !x.menu.top && trailTo(x.menu.items, current));
      if (holds) shown = holds.menu.key;
    }
    function pick() {
      const all = menus();
      if (!all.length) return null;
      return all.find((x) => x.menu.key === shown) || all.find((x) => x.menu.key === chosen)
        || all.find((x) => !x.menu.top) || all[0];
    }

    // Whether an entry can be picked up: the menu has a writer, the entry
    // is in its file (an autogenerated branch isn't), and it isn't code.
    //   it.fm — placed by front matter (an autogenerated folder's page)
    //   it.meta — listed in a per-folder meta file (Fumadocs, Nextra, Rspress)
    function movable(menu, it, auto) {
      if (it.fm) return true;
      if (it.meta) return !!menu.editable;
      return !!menu.editable && !auto && it.kind !== 'dyn' && it.kind !== 'auto' && !it.noEdit
        && (it.line != null || !!it.span || !!it.jpath);
    }
    // Whether something can land `where` relative to `it`
    function fits(menu, it, where) {
      if (it.kind === 'dyn' || it.kind === 'auto' || it.noEdit) return false;
      // folder-built entries move among their own folder's (Just the Docs:
      // any page can become a parent)
      if (it.fm) return where !== 'inside' || (it.fm === 'jtd' && !!it.file);
      if (it.meta) return where !== 'inside' && !!menu.editable;
      if (where !== 'inside') return it.line != null || !!it.span || !!it.jpath;
      const k = menu.source && menu.source.kind;
      if (k === 'mdlist') return it.line != null && it.kind !== 'sep';
      if (k === 'yamllist') return it.line != null && it.kind === 'group' && !it.file;
      if (k === 'yamlmap') return it.line != null && !!it.ychild;
      if (k === 'json') return !!it.listPath;
      return !!it.itemsSpan;
    }
    // what's being dragged may land here at all: folder-built entries only
    // beside their siblings, and nothing else among them
    function accepts(it, id) {
      if (!drag) return false;
      const tree = !!(it.fm || it.meta);
      if (drag.file) return !tree;
      if (drag.tree !== tree) return false;
      if (tree && it.fm !== 'jtd' && parentId(drag.at) !== parentId(id)) return false;
      return true;
    }
    function zone(e, row, menu, it) {
      const r = row.getBoundingClientRect();
      const y = (e.clientY - r.top) / r.height;
      const into = fits(menu, it, 'inside');
      const beside = fits(menu, it, 'before');
      if (into && (!beside || (y > 0.25 && y < 0.75))) return 'inside';
      if (!beside) return null;
      return y < 0.5 ? 'before' : 'after';
    }
    function clearDrop() {
      for (const el of box.querySelectorAll('.drop-before, .drop-after, .drop-inside')) {
        el.classList.remove('drop-before', 'drop-after', 'drop-inside');
      }
      $('smTree').classList.remove('drop-end');
    }
    const setOpen = (key, id, on) => {
      const s = shut.get(key) || new Set(), o = opened.get(key) || new Set();
      if (on) { s.delete(id); o.add(id); } else { s.add(id); o.delete(id); }
      shut.set(key, s);
      opened.set(key, o);
    };

    // ------------------------------------------------------------- drawing

    function paintHead(all, cur) {
      const sys = $('smSys'), sel = $('smPick'), dead = $('smDead'), info = $('smInfo'), btn = $('smInfoBtn');
      info.textContent = '';
      if (!cur) {
        sys.textContent = 'No docs-site menu here';
        sel.hidden = dead.hidden = btn.hidden = true;
        info.hidden = true;
        return;
      }
      const { site, menu } = cur;
      sys.textContent = site.label;
      sys.title = site.label + (site.root ? ' — ' + site.root + '/' : '');
      // the picker: every menu, grouped by site when there are several
      sel.textContent = '';
      sel.hidden = all.length < 2;
      const multiSite = sites.length > 1;
      for (const s of sites) {
        const parent = multiSite ? document.createElement('optgroup') : sel;
        if (multiSite) { parent.label = s.label + (s.root ? ' — ' + s.root : ''); sel.appendChild(parent); }
        for (const m of s.menus) {
          const o = document.createElement('option');
          o.value = m.key;
          o.textContent = m.label;
          o.selected = m.key === menu.key;
          parent.appendChild(o);
        }
      }
      const deadHere = site.dead.filter((d) => d.menu === menu.key && !d.generated);
      dead.hidden = !deadHere.length;
      dead.textContent = '✗ ' + deadHere.length;
      dead.title = deadHere.length === 1 ? '1 entry points at nothing — click to show it'
        : deadHere.length + ' entries point at nothing — click to show them';
      dead.onclick = () => revealDead(menu);
      btn.hidden = false;
      btn.classList.toggle('on', infoOpen);
      info.hidden = !infoOpen;
      if (!infoOpen) return;

      // the details
      const line = (text, cls) => {
        const d = document.createElement('div');
        d.className = 'smLine' + (cls ? ' ' + cls : '');
        if (text) d.textContent = text;
        info.appendChild(d);
        return d;
      };
      const from = menu.source && menu.source.file;
      if (from && /\.[^/]+$/.test(from)) {
        const d = line('', '');
        const a = document.createElement('a');
        a.textContent = from;
        a.title = 'Open it' + (menu.source.line != null ? ' at line ' + (menu.source.line + 1) : '');
        a.onclick = () => onOpenAt(abs(from), menu.source.line || 0);
        d.append('Written in ', a);
      } else if (menu.auto) line('Generated from the folders' + (from ? ' in ' + from + '/' : '') + '.');
      if (menu.note) line(menu.note);
      if (menu.complete === false) line('Part of it is built by code — shown as far as it can be read.');
      if (menu.eject) {
        // put together from pieces: readable whole, but no one literal to edit
        const d = line('It’s put together from several pieces, so Nib can’t edit it in place. ', '');
        const a = document.createElement('a');
        a.textContent = 'Move it to a JSON file…';
        a.onclick = () => ejectMenu(menu);
        d.appendChild(a);
      } else if (!menu.editable) line('Nib can’t edit this kind of menu yet.');
      const gen = site.dead.filter((d) => d.menu === menu.key && d.generated);
      if (gen.length) {
        const dirs = [...new Set(gen.map((d) => String(d.link).replace(/^\.?\//, '').split('/')[0]))];
        line(gen.length + ' entries point into ' + dirs.map((x) => x + '/').join(', ')
          + ', which isn’t in the folder — probably generated when the site builds.');
      }
      if (deadHere.length) line(deadHere.length === 1 ? '1 entry points at nothing.' : deadHere.length + ' entries point at nothing.', 'bad');
      for (const n of site.notes) line(n);
      if (current && current === from) line('You’re in the file this menu is written in.', 'here');
      else if (current) {
        const trail = trailTo(menu.items, current);
        if (trail) line('This page: ' + textAt(menu.items, trail).join(' › '), 'here');
        else if (current.startsWith(site.content ? site.content + '/' : '')) {
          const elsewhere = all.filter((x) => x.menu.key !== menu.key && trailTo(x.menu.items, current));
          line(elsewhere.length ? 'This page is in ' + elsewhere.map((x) => x.menu.label).join(', ') + ', not here.'
            : 'This page isn’t in any menu.', 'here off');
        }
      }
    }

    function paint({ scroll = false } = {}) {
      const list = $('smTree'), orph = $('smOrphans');
      list.textContent = '';
      orph.textContent = '';
      rows = [];
      const all = menus();
      const cur = pick();
      paintHead(all, cur);
      if (!cur) return;
      const { site, menu } = cur;
      const from = menu.source && menu.source.file;
      const isFile = from && /\.[^/]+$/.test(from);
      const trail = current && trailTo(menu.items, current);
      const open = new Set(trail ? trail.slice(0, -1) : []);
      const hand = shut.get(menu.key) || new Set();
      const handOpen = opened.get(menu.key) || new Set();

      const draw = (items, depth, pre, auto) => {
        items.forEach((it, i) => {
          const id = pre + i;
          const row = document.createElement('div');
          row.className = 'smRow k-' + it.kind + (it.missing ? (it.generated ? ' generated' : ' missing') : '')
            + (it.file && it.file === current ? ' cur' : '') + (id === cursor ? ' kc' : '');
          row.style.paddingLeft = (4 + depth * 12) + 'px';
          row.dataset.id = id;
          const kids = !!(it.items && it.items.length);
          // a fold by hand wins; otherwise collapsed: true, unless this page is inside
          const isShut = kids && (hand.has(id) || (it.collapsed && !handOpen.has(id) && !open.has(id)));
          rows.push({ id, it, kids, isShut, auto });
          const tw = document.createElement('span');
          tw.className = 'smTw';
          tw.textContent = kids ? (isShut ? '▸' : '▾') : '';
          row.appendChild(tw);
          if (renaming === id) {
            const input = document.createElement('input');
            input.className = 'smEdit';
            input.value = typed !== null ? typed : it.text || '';
            input.spellcheck = false;
            row.appendChild(input);
            setTimeout(() => {
              if (!input.isConnected) return;
              input.focus();
              if (typed === null) input.select();
            });
            input.oninput = () => { typed = input.value; };
            let done = false;
            const finish = (commit) => {
              if (done) return;
              done = true;
              const value = input.value.trim();
              renaming = null;
              typed = null;
              paint();
              box.focus();
              if (commit && value && value !== it.text) edit(menu, { kind: 'rename', at: id, text: value }, 'Rename “' + (it.text || '') + '”');
            };
            input.onkeydown = (e) => {
              e.stopPropagation();
              if (e.key === 'Enter') { e.preventDefault(); finish(true); }
              else if (e.key === 'Escape') { e.preventDefault(); finish(false); }
            };
            input.onblur = () => { if (input.isConnected) finish(true); };
          } else {
            const label = document.createElement('span');
            label.className = 'smTx';
            label.textContent = it.kind === 'sep' && !it.text ? '' : it.text || (it.kind === 'auto' ? 'Autogenerated' : '(untitled)');
            row.appendChild(label);
          }
          if (it.kind === 'link') { const k = document.createElement('span'); k.className = 'smK'; k.textContent = '↗'; row.appendChild(k); }
          if (it.missing && !it.generated) { const k = document.createElement('span'); k.className = 'smK'; k.textContent = '✗'; row.appendChild(k); }
          row.title = it.generated ? it.link + ' — not in the folder; generated at build time?'
            : it.missing ? 'Points at ' + it.link + ' — there’s no such page'
              : it.kind === 'dyn' ? 'Built by code: ' + (it.note || '')
                : it.kind === 'auto' ? 'Generated from the folder, not listed by hand'
                  : it.kind === 'link' ? it.href
                    : it.file || '';
          const toggle = () => { setOpen(menu.key, id, isShut); paint(); };
          tw.onclick = (e) => { e.stopPropagation(); if (kids) toggle(); };
          row.onclick = () => {
            if (renaming === id) return;
            cursor = id;
            box.focus({ preventScroll: true });
            if (it.file) onOpen(abs(it.file), true);
            else if (it.kind === 'link') onExternal(it.href);
            else if (kids) { toggle(); return; }
            paint();
          };
          // a double-click keeps the page — and opens a group that is one
          row.ondblclick = () => {
            if (renaming === id) return;
            if (it.file) onOpen(abs(it.file), false);
            if (kids && isShut) toggle();
          };
          const can = movable(menu, it, auto);
          row.oncontextmenu = (e) => {
            e.preventDefault();
            e.stopPropagation();
            cursor = id;
            paint();
            const acts = [];
            if (it.file) acts.push({ label: 'Open', fn: () => onOpen(abs(it.file), false) });
            if (it.kind === 'link') acts.push({ label: 'Open in Browser', fn: () => onExternal(it.href) });
            if (isFile) acts.push({ label: 'Show in ' + from.split('/').pop(), fn: () => onOpenAt(abs(from), it.line != null ? it.line : (menu.source.line || 0)) });
            if (can) {
              acts.push({ sep: true });
              acts.push({ label: 'Rename', fn: () => startRename(id) });
              if (current && !trail && !it.fm && !it.meta && fits(menu, it, 'after')) {
                acts.push({ label: 'Add This Page After', fn: () => edit(menu, { kind: 'add', file: current, to: id, where: 'after' }, 'Add this page') });
              }
              if (current && !trail && !it.fm && !it.meta && fits(menu, it, 'inside')) {
                acts.push({ label: 'Add This Page Inside', fn: () => edit(menu, { kind: 'add', file: current, to: id, where: 'inside' }, 'Add this page') });
              }
              // a folder-built entry can't be taken out, only hidden
              acts.push({ label: it.fm || it.meta ? 'Hide from Menu' : 'Remove from Menu', fn: () => remove(menu, id, it) });
            }
            if (acts.length) showMenu(it.text || 'Entry', acts, e.clientX, e.clientY);
          };
          // drag to move: the top quarter drops before, the bottom quarter
          // after, the middle into (when the entry can hold others)
          if (can) {
            row.draggable = true;
            row.ondragstart = (e) => {
              drag = { at: id, text: it.text, tree: !!(it.fm || it.meta) };
              e.dataTransfer.effectAllowed = 'move';
              try { e.dataTransfer.setData('text/plain', it.text || ''); } catch { /* fine */ }
              row.classList.add('dragging');
            };
            row.ondragend = () => { drag = null; row.classList.remove('dragging'); clearDrop(); };
          }
          if ((menu.editable && !auto && it.kind !== 'dyn') || it.fm) {
            row.ondragover = (e) => {
              if (!drag || !accepts(it, id) || (drag.at && (drag.at === id || id.startsWith(drag.at + '.')))) return;
              const where = zone(e, row, menu, it);
              if (!where) return;
              e.preventDefault();
              e.dataTransfer.dropEffect = drag.at ? 'move' : 'copy';
              clearDrop();
              row.classList.add('drop-' + where);
            };
            row.ondragleave = () => row.classList.remove('drop-before', 'drop-after', 'drop-inside');
            row.ondrop = (e) => {
              e.preventDefault();
              e.stopPropagation();
              const where = zone(e, row, menu, it);
              clearDrop();
              if (!drag || !where || !accepts(it, id)) return;
              const d = drag;
              drag = null;
              cursor = null;
              if (d.at) edit(menu, { kind: 'move', at: d.at, to: id, where }, 'Move “' + (d.text || 'entry') + '”');
              else edit(menu, { kind: 'add', file: d.file, to: id, where }, 'Add “' + d.file.split('/').pop() + '”');
            };
          }
          list.appendChild(row);
          if (kids && !isShut) draw(it.items, depth + 1, id + '.', auto || it.kind === 'auto');
        });
      };
      draw(menu.items, 0, '', false);
      list.onmousedown = () => { if (orphansOpen) { orphansOpen = false; paint(); } };
      // dropping on the empty space under the last row: the end of the menu
      list.ondragover = (e) => {
        if (!drag || drag.tree || !menu.editable || menu.auto || menu.source.kind === 'meta-tree' || e.target !== list) return;
        e.preventDefault();
        clearDrop();
        list.classList.add('drop-end');
      };
      list.ondragleave = (e) => { if (e.target === list) list.classList.remove('drop-end'); };
      list.ondrop = (e) => {
        if (e.target !== list || !drag || drag.tree || !menu.editable || menu.auto || menu.source.kind === 'meta-tree') return;
        e.preventDefault();
        clearDrop();
        const d = drag;
        drag = null;
        if (d.at) edit(menu, { kind: 'move', at: d.at, to: null }, 'Move “' + (d.text || 'entry') + '”');
        else edit(menu, { kind: 'add', file: d.file, to: null }, 'Add “' + d.file.split('/').pop() + '”');
      };
      if (scroll) {
        const el = list.querySelector('.smRow.kc') || list.querySelector('.smRow.cur');
        if (el) el.scrollIntoView({ block: 'nearest' });
      }

      // what no menu reaches, across this site: a bar at the bottom, opening
      // as a sheet over the menu (it can be long — a site's every locale)
      orph.classList.toggle('open', orphansOpen && site.orphans.length > 0);
      if (site.orphans.length) {
        const head = document.createElement('div');
        head.className = 'sfFile';
        head.innerHTML = '<span class="sfTwist">▾</span><span class="sfName"></span><span class="sfDir"></span><span class="sfN"></span>';
        head.querySelector('.sfTwist').textContent = orphansOpen ? '▾' : '▴';
        head.querySelector('.sfName').textContent = 'Not in any menu';
        head.querySelector('.sfN').textContent = site.orphans.length;
        head.title = 'Pages under ' + (site.content || 'the folder') + '/ that no menu of this site links to'
          + (menu.editable && !menu.auto && menu.source.kind !== 'meta-tree' ? ' — drag one into the menu to add it' : '');
        head.onclick = () => { orphansOpen = !orphansOpen; paint(); if (orphansOpen) orph.scrollTop = 0; };
        orph.appendChild(head);
        if (orphansOpen) {
          for (const rel of site.orphans) {
            const row = document.createElement('div');
            row.className = 'smRow k-page orphan' + (rel === current ? ' cur' : '');
            row.style.paddingLeft = '16px';
            const name = rel.split('/').pop();
            const tx = document.createElement('span');
            tx.className = 'smTx';
            tx.textContent = name;
            const dir = document.createElement('span');
            dir.className = 'sfDir';
            dir.textContent = rel.slice(site.content ? site.content.length + 1 : 0, rel.length - name.length).replace(/\/$/, '');
            row.append(tx, dir);
            row.title = rel;
            row.onclick = () => onOpen(abs(rel), true);
            row.ondblclick = () => onOpen(abs(rel), false);
            // a page can be added to a menu written by hand — one built from
            // the folders already has every page it's going to have
            const addable = menu.editable && !menu.auto && menu.source.kind !== 'meta-tree';
            if (addable) {
              row.draggable = true;
              row.ondragstart = (e) => {
                drag = { file: rel };
                e.dataTransfer.effectAllowed = 'copy';
                try { e.dataTransfer.setData('text/plain', rel); } catch { /* fine */ }
              };
              row.ondragend = () => { drag = null; clearDrop(); };
            }
            row.oncontextmenu = (e) => {
              e.preventDefault();
              const acts = [{ label: 'Open', fn: () => onOpen(abs(rel), false) }];
              if (addable) acts.push({ label: 'Add to the End of the Menu', fn: () => edit(menu, { kind: 'add', file: rel, to: null }, 'Add “' + name + '”') });
              showMenu(name, acts, e.clientX, e.clientY);
            };
            orph.appendChild(row);
          }
        }
      }
    }

    // open the groups holding dead entries and put the cursor on the first
    function revealDead(menu) {
      let first = null;
      const walk = (items, pre) => items.forEach((it, i) => {
        const id = pre + i;
        if (it.missing && !it.generated) {
          if (!first) first = id;
          let p = parentId(id);
          while (p) { setOpen(menu.key, p, true); p = parentId(p); }
        }
        if (it.items) walk(it.items, id + '.');
      });
      walk(menu.items, '');
      if (first) cursor = first;
      paint({ scroll: true });
      box.focus({ preventScroll: true });
    }

    // --------------------------------------------------------------- edits

    async function edit(menu, op, what) {
      let r;
      try { r = await onEdit(menu.key, op, what); } catch (e) { r = { error: String(e && e.message || e) }; }
      if (!r || r.error) { toast((r && r.error) || 'Couldn’t change the menu.'); return false; }
      sites = r.sites || sites;
      shown = menu.key;
      follow();
      paint({ scroll: true });
      return true;
    }
    async function history(redo) {
      let r;
      try { r = await (redo ? onRedo() : onUndo()); } catch { r = null; }
      if (!r || r.error) { toast((r && r.error) || (redo ? 'Nothing to redo.' : 'Nothing to undo.')); return; }
      if (r.label) toast((redo ? 'Redo: ' : 'Undo: ') + r.label);
      sites = r.sites || sites;
      follow();
      paint({ scroll: true });       // the cursor stays where it was
    }
    async function ejectMenu(menu) {
      const ok = await tiny.dialog.confirm('Move this sidebar to a JSON file?', {
        detail: 'Nib writes the sidebar, as the site builds it now, to a .json file next to the config, '
          + 'and the config imports it in place of the pieces. From then on it can be edited here. '
          + 'The pieces it was built from are left where they are. ⌘Z undoes it.',
        ok: 'Move to JSON', cancel: 'Cancel',
      });
      if (ok) edit(menu, { kind: 'eject' }, 'Move Sidebar to JSON');
    }
    function startRename(id) {
      const cur = pick();
      if (!cur) return;
      const it = itemAt(cur.menu, id);
      const row = rows.find((r) => r.id === id);
      if (!it || !movable(cur.menu, it, row && row.auto)) return;
      cursor = id;
      renaming = id;
      typed = null;
      paint();
    }
    async function remove(menu, id, it) {
      const n = (it.items || []).length;
      if (n) {
        const ok = await tiny.dialog.confirm('Remove “' + (it.text || '') + '” and the ' + (n === 1 ? 'entry' : n + ' entries') + ' under it from the menu?', {
          detail: 'The pages stay where they are — only the menu changes.', ok: 'Remove', cancel: 'Cancel',
        });
        if (!ok) return;
      }
      const next = rows[rows.findIndex((r) => r.id === id) - 1];
      if (await edit(menu, { kind: 'remove', at: id }, 'Remove “' + (it.text || 'entry') + '”')) {
        cursor = next ? next.id : null;
        paint();
      }
    }
    // ⌘↑ / ⌘↓: swap with the sibling above or below
    async function nudge(menu, id, dir) {
      const p = parentId(id);
      const i = +id.split('.').pop();
      const sibs = p ? (itemAt(menu, p) || {}).items : menu.items;
      const j = i + dir;
      if (!sibs || j < 0 || j >= sibs.length) return;
      const pre = p ? p + '.' : '';
      if (await edit(menu, { kind: 'move', at: id, to: pre + j, where: dir < 0 ? 'before' : 'after' }, 'Move “' + (sibs[i].text || 'entry') + '”')) {
        cursor = pre + j;
        paint({ scroll: true });
      }
    }

    // ------------------------------------------------------------ keyboard

    box.addEventListener('keydown', (e) => {
      if (e.target !== box) return;               // the rename field has its own keys
      e.stopPropagation();                        // the file tree listens on the same panel
      const cur = pick();
      if (!cur) return;
      const { menu } = cur;
      const mod = e.metaKey || e.ctrlKey;
      const k = e.key;
      if (mod && (k === 'z' || k === 'Z' || k === 'y')) {
        e.preventDefault();
        history(k === 'y' || e.shiftKey);
        return;
      }
      if (!rows.length) return;
      const i = rows.findIndex((r) => r.id === cursor);
      const r = rows[i] || null;
      const go = (row, { preview = true } = {}) => {
        if (!row) return;
        cursor = row.id;
        paint({ scroll: true });
        clearTimeout(previewTimer);
        if (preview && row.it.file) previewTimer = setTimeout(() => onOpen(abs(row.it.file), true), 180);
      };
      if (mod && (k === 'ArrowUp' || k === 'ArrowDown')) {
        e.preventDefault();
        if (r && movable(menu, r.it, r.auto)) nudge(menu, r.id, k === 'ArrowUp' ? -1 : 1);
      } else if (k === 'ArrowDown') { e.preventDefault(); go(rows[i < 0 ? 0 : Math.min(rows.length - 1, i + 1)]); }
      else if (k === 'ArrowUp') { e.preventDefault(); go(rows[i < 0 ? 0 : Math.max(0, i - 1)]); }
      else if (k === 'Home') { e.preventDefault(); go(rows[0]); }
      else if (k === 'End') { e.preventDefault(); go(rows[rows.length - 1]); }
      else if (k === 'ArrowRight') {
        e.preventDefault();
        if (r && r.kids && r.isShut) { setOpen(menu.key, r.id, true); paint(); }
        else if (r && r.kids) go(rows[i + 1], { preview: false });
      } else if (k === 'ArrowLeft') {
        e.preventDefault();
        if (r && r.kids && !r.isShut) { setOpen(menu.key, r.id, false); paint(); }
        else if (r && parentId(r.id)) go(rows.find((x) => x.id === parentId(r.id)), { preview: false });
      } else if (k === 'Enter' && mod) {
        e.preventDefault();
        clearTimeout(previewTimer);
        if (r && r.it.file) onOpen(abs(r.it.file), false);
      } else if (k === 'Enter') {
        e.preventDefault();
        if (r) startRename(r.id);
      } else if (k === ' ') {
        e.preventDefault();
        if (r && r.it.file) onOpen(abs(r.it.file), true);
        else if (r && r.it.kind === 'link') onExternal(r.it.href);
      } else if ((k === 'Backspace' && mod) || k === 'Delete') {
        e.preventDefault();
        if (r && movable(menu, r.it, r.auto)) remove(menu, r.id, r.it);
      } else if (k === 'Escape' && orphansOpen) {
        e.preventDefault();
        orphansOpen = false;
        paint();
      } else if (k === 'Escape') {
        e.preventDefault();
        clearTimeout(previewTimer);
        if (onEscape) onEscape();
      }
    });

    // Edit ▸ Undo / Redo follow the keyboard: the panel's while it has it
    let focused = false;
    const focusNow = () => {
      const on = document.activeElement === box;
      if (on === focused) return;
      focused = on;
      onFocus && onFocus(on);
    };
    box.addEventListener('focus', focusNow);
    box.addEventListener('blur', () => setTimeout(focusNow, 0));   // after focus has landed elsewhere
    // another window taking the keyboard takes Edit ▸ Undo with it
    window.addEventListener('blur', () => { if (focused) { focused = false; onFocus && onFocus(false); } });
    window.addEventListener('focus', () => setTimeout(focusNow, 0));

    $('smPick').onchange = (e) => {
      chosen = shown = e.target.value;
      cursor = null;
      try { localStorage.setItem(KEY, chosen); } catch { /* fine */ }
      paint();
    };
    $('smInfoBtn').onclick = () => {
      infoOpen = !infoOpen;
      try { localStorage.setItem(INFO, infoOpen ? '1' : '0'); } catch { /* fine */ }
      paint();
    };

    async function refresh() {
      const n = ++ask;
      let r;
      try { r = await fetch(); } catch { r = null; }
      if (n !== ask) return;
      const was = sites.length > 0;
      sites = (r && r.sites) || [];
      follow();
      // never under a drag or a rename — the row being held would be rebuilt
      if (!box.hidden && !drag && renaming === null) paint();
      if (was !== sites.length > 0) onChange && onChange();
    }

    return {
      refresh,
      has: () => sites.length > 0,
      showing(p) {
        const r = root();
        const rel = p && r && p.startsWith(r + '/') ? p.slice(r.length + 1) : null;
        if (rel === current) return;
        current = rel;
        follow();
        // a page you go to is revealed, even inside a group folded by hand
        const cur = pick();
        const trail = cur && current && trailTo(cur.menu.items, current);
        if (trail) for (const id of trail.slice(0, -1)) setOpen(cur.menu.key, id, true);
        if (!box.hidden && renaming === null) paint({ scroll: true });
      },
      paint: () => { if (!box.hidden && renaming === null) paint({ scroll: true }); },
      focus() { box.focus({ preventScroll: true }); },
      history,
      clear() { sites = []; current = null; cursor = null; },
    };
  }

  window.setupSiteMenu = setupSiteMenu;
})();
