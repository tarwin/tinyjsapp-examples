//
// No menu file at all: the tree is the toctree directives, starting at the
// root document and followed page by page. Read-only — the "menu" is spread
// through the documents themselves.

const sphinx = {
  id: 'sphinx', label: 'Sphinx',
  find: (ctx) => ctx.rels.filter((r) => /(^|\/)conf\.py$/.test(r)).map((config) => ({ config, root: dirOf(config) })),
  async read(ctx, { config, root }) {
    const conf = (await ctx.read(config)) || '';
    const rd = /^(?:root_doc|master_doc)\s*=\s*['"]([^'"]+)['"]/m.exec(conf);
    const exts = ['rst', 'md', 'ipynb', 'txt'];
    const start = resolve(ctx, (rd ? rd[1] : 'index'), { root, from: root, exts });
    if (!start) return null;
    const seen = new Set([start]);
    const walk = async (rel, depth) => {
      if (depth > 8) return [];
      const text = (await ctx.read(rel)) || '';
      const out = [];
      for (const tt of toctrees(text, extOf(rel) === 'rst')) {
        const kids = [];
        for (const e of tt.entries) {
          if (e.glob) { kids.push({ text: e.target, kind: 'auto' }); continue; }
          if (e.target === 'self') continue;
          if (isExternal(e.target)) { kids.push({ text: e.title || e.target, kind: 'link', href: e.target }); continue; }
          const f = resolve(ctx, e.target, { root, from: dirOf(rel), exts });
          const node = page(e.title || '', e.target, f);
          if (f && !seen.has(f)) {
            seen.add(f);
            const sub = await walk(f, depth + 1);
            if (sub.length) { node.kind = 'group'; node.items = sub; }
          }
          kids.push(node);
        }
        if (tt.caption) out.push(group(tt.caption, kids));
        else out.push(...kids);
      }
      return out;
    };
    const items = await walk(start, 0);
    await fillTitles(ctx, items);
    return { content: root, notes: [], menus: [{ id: 'toctree', label: 'Toctree', scope: null,
      source: { file: start, kind: 'toctree' }, editable: false, complete: !JSON.stringify(items).includes('"auto"'), items }] };
  },
};

function toctrees(text, rst) {
  const out = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    let body = null;
    if (rst && /^\s*\.\.\s+toctree::/.test(lines[i])) {
      body = [];
      const ind0 = lines[i].match(/^\s*/)[0].length;
      for (i++; i < lines.length; i++) {
        if (lines[i].trim() && lines[i].match(/^\s*/)[0].length <= ind0) { i--; break; }
        body.push(lines[i].trim());
      }
    } else if (!rst && /^\s*(`{3,}|:{3,})\s*\{toctree\}/.test(lines[i])) {
      const fence = lines[i].trim().match(/^(`{3,}|:{3,})/)[1];
      body = [];
      for (i++; i < lines.length && !lines[i].trim().startsWith(fence); i++) body.push(lines[i].trim());
    }
    if (!body) continue;
    const tt = { caption: null, entries: [] };
    let glob = false;
    let inYaml = false;
    for (const l of body) {
      if (l === '---') { inYaml = !inYaml; continue; }
      const opt = inYaml ? /^(\w+)\s*:\s*(.*)$/.exec(l) : /^:(\w+):\s*(.*)$/.exec(l);
      if (opt) {
        if (opt[1] === 'caption') tt.caption = opt[2].trim();
        if (opt[1] === 'glob') glob = true;
        continue;
      }
      if (!l || inYaml) continue;
      const titled = /^(.*\S)\s*<([^>]+)>$/.exec(l);
      const target = titled ? titled[2] : l;
      tt.entries.push({ title: titled ? titled[1] : null, target, glob: glob && /[*?[]/.test(target) });
    }
    out.push(tt);
  }
  return out;
}

