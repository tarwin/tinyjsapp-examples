// Site menus: what a docs site's sidebar (and its other menus) look like,
// read from wherever that site keeps them — VitePress's config, Docusaurus's
// sidebars.js, mkdocs.yml, a GitBook SUMMARY.md, Fumadocs' meta.json files,
// front matter weights — and turned into ONE shape, so the panel that shows
// them, "where is this page", and "which pages does no menu reach" are
// written once.
//
// The shape:
//
//   site  { system, label, root, config, content, menus: [menu], notes: [] }
//   menu  { id, label, scope, source, editable, complete, items: [item] }
//   item  { text, kind, link?, file?, href?, items?, collapsed?, note? }
//
// kind is 'page' (a document — `file` is its project-relative path, or null
// when the link lands on nothing), 'group' (a heading with children, which may
// itself have a page), 'link' (external), 'sep' (a divider or a part title),
// 'dyn' (code we didn't run — `note` says what), 'auto' (an autogenerated
// branch, already expanded into `items` where we could).
//
// `complete` is false when part of a menu is code we didn't run: such a menu
// can still be shown, but "no menu reaches this page" would be a guess, so
// orphans aren't reported for its site.
//
// Everything here is plain data in and out — `ctx.read(rel)` is the only
// door to the disk — so it runs under txiki in the app and under node in a
// test, and never needs the project to build or its dependencies installed.

