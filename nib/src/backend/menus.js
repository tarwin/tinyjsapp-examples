    if (fm.sidebar && fm.sidebar.hidden) { ctx.hidden.add(f); continue; }
    entries.push({ pos: num(fm.sidebar && fm.sidebar.order), name: baseOf(f), node: page(await starLabel(ctx, f), null, f, { fm: 'starlight' }) });
